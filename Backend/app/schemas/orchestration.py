"""Pydantic schemas for Phase 7 Intelligent Model Orchestrator."""

from datetime import datetime
from typing import List, Dict, Any, Optional, Union
from pydantic import BaseModel, Field



class SelectedModelItem(BaseModel):
    """A model or pipeline selected for execution by the orchestrator."""
    capability_id: str
    capability_name: str
    model_id: str
    model_name: str
    modality: str
    asset_id: str
    asset_filename: str
    status: str  # 'ready', 'not_configured'
    estimated_ram_mb: int = 512
    estimated_latency_ms: int = 500
    device: str = "cpu"
    selection_reason: str


class SkippedCapabilityItem(BaseModel):
    """A capability skipped during orchestration with deterministic auditable rationale."""
    capability_id: str
    capability_name: str
    expected_modality: str
    skip_reason: str
    status: str  # 'skipped_no_asset', 'skipped_not_configured', 'skipped_incompatible', 'skipped_resource_constraint'


class ExecutionStepItem(BaseModel):
    """A step in the computed topological execution order."""
    step_number: int
    node_id: str
    label: str
    node_type: str
    modality: str
    status: str
    dependencies: List[str] = Field(default_factory=list)


class OrchestrationPlanCreate(BaseModel):
    """Request schema to generate an orchestration plan for a clinical case."""
    case_id: Optional[str] = None
    symptoms_context: Optional[Union[str, List[str]]] = None
    force_replan: bool = False



class OrchestrationPlanResponse(BaseModel):
    """Full auditable execution plan generated by the Intelligent Model Orchestrator."""
    id: str
    case_id: str
    patient_id: str
    status: str
    input_modalities: List[str]
    symptoms_context: Optional[str] = None
    selected_models: List[SelectedModelItem]
    skipped_capabilities: List[SkippedCapabilityItem]
    execution_order: List[ExecutionStepItem]
    dag: Dict[str, Any]
    selection_reasons: Dict[str, str]
    resource_snapshot: Dict[str, Any]
    summary: str
    created_at: datetime
    updated_at: datetime
